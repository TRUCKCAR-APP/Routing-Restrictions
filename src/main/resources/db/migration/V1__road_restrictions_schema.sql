CREATE TABLE IF NOT EXISTS road_restrictions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restriction_code      VARCHAR(255)  NOT NULL,
    title                 VARCHAR(255)  NOT NULL,
    description           VARCHAR(1000),
    restriction_type      VARCHAR(255)  NOT NULL,
    severity              VARCHAR(255)  NOT NULL,
    road_corridor         VARCHAR(255)  NOT NULL,
    department            VARCHAR(255),
    max_clearance_meters  DOUBLE PRECISION,
    max_gross_weight_tons DOUBLE PRECISION,
    max_axle_weight_tons  DOUBLE PRECISION,
    latitude              DOUBLE PRECISION,
    longitude             DOUBLE PRECISION,
    applies_from          TIMESTAMP(6),
    applies_to            TIMESTAMP(6),
    is_active             BOOLEAN       NOT NULL,
    created_at            TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_road_restrictions_code UNIQUE (restriction_code),
    CONSTRAINT road_restrictions_restriction_type_check CHECK (restriction_type IN
        ('GALIBO_ALTURA', 'PESO_BRUTO', 'PESO_POR_EJE', 'HORARIO_FESTIVO', 'CIERRE_PROGRAMADO', 'PASO_RESTRINGIDO')),
    CONSTRAINT road_restrictions_severity_check CHECK (severity IN ('INFORMATIVA', 'PRECAUCION', 'BLOQUEO_TOTAL'))
);

CREATE INDEX IF NOT EXISTS idx_restriction_type ON road_restrictions (restriction_type);
CREATE INDEX IF NOT EXISTS idx_restriction_corridor ON road_restrictions (road_corridor);
CREATE INDEX IF NOT EXISTS idx_restriction_active ON road_restrictions (is_active);
